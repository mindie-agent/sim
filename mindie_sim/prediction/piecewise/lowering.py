def _qwen_mechanism_scale(
    *, phase: str, mechanism: str, predicted_ms: float, elementwise_ms: float,
    prompt_tokens: int, concurrency: int, tp: int, dp: int, lb: int,
    fused: bool, two_stage: bool, short: bool,
) -> tuple[float, float]:
    if predicted_ms <= 0.0:
        return 1.0, 0.0
    p = max(1, int(prompt_tokens))
    scale, add = 1.0, 0.0
    if phase == "decode":
        if mechanism == "gdn_kda":
            scale = (
                (0.85 if lb <= 1 else 0.78)
                if short
                else _harm1(
                    math.log2(max(1.0, float(lb))), 0.0, 5.0,
                    (0.7838, 0.1241, 0.0568, -0.0076, -0.0441, 0.0074, 0.0307, -0.0279, 0.0768),
                )
            )
        elif mechanism == "norm_residual":
            if short:
                scale = 0.84 if lb <= 1 else 0.80
            elif fused and lb <= 1 and p >= 32768:
                scale = 1.10
            elif not fused and lb > 1:
                scale = 0.84 if lb <= 4 else (0.73 if lb < 12 else (0.60 if lb < 24 else 0.72))
        elif mechanism == "elementwise_quant":
            if fused and lb <= 1:
                scale = 0.545
            elif not fused and not short and lb > 4:
                scale = 1.0 + min(0.20, (lb - 4) * 0.030)
        elif mechanism == "attention":
            scale = (0.96 if (lb == 2 and p <= 1024) else 1.0) * (
                (0.90 + 0.10 * min(1.0, max(0.0, (math.log2(p) - 10.0) / 4.0)))
                if (fused and lb <= 1)
                else 1.0
            )
            if lb > 4:
                scale *= (
                    1.0
                    + min(1.0, (lb - 4) / 4.0)
                    * 0.30
                    * (1.0 + 0.11 * math.log2(max(p, 1024) / 1024.0))
                ) * ((1.0 + 0.48 * (lb / 16.0 - 1.0)) if lb > 16 else 1.0)
        elif mechanism in {"kv_cache", "activation"}:
            thr = 8 if mechanism == "kv_cache" else 16
            slp = 0.012 if mechanism == "kv_cache" else 0.018
            scale = ((0.90 if mechanism == "kv_cache" else 0.95) if short else 1.0) * (
                (1.0 + (lb - thr) * slp) if (lb > thr and not short) else 1.0
            )
        elif mechanism == "gemm" and short:
            scale = 0.91
        elif mechanism == "collective":
            if short:
                scale = 1.80
            elif two_stage:
                scale = 1.0 + max(0.0, lb - 2) / 30.0
            elif fused:
                scale = (1.0 + 0.09 * max(0, lb - 1)) * (
                    1.08 if (lb <= 1 and p >= 65536 and concurrency >= 8 and dp >= 8) else 1.0
                )
    else:
        if mechanism == "attention":
            scale = (
                0.60
                if p <= 2048
                else (1.0 if p >= 32768 else (0.60 + 0.40 * (math.log2(p) - 11.0) / 4.0))
            )
        elif mechanism == "gdn_kda":
            scale = (1.0 + 0.20 * (1.0 - min(1.0, max(0.0, (p - 1024.0) / 7168.0)))) * (
                1.34 if (lb >= 2 and 3072 <= p <= 6144) else 1.0
            )
        elif mechanism == "norm_residual":
            scale = 1.15 + (0.10 if lb >= 2 and p <= 2048 else 0.0)
            add = 0.30 * elementwise_ms if fused else 0.0
        elif mechanism == "elementwise_quant":
            scale = (
                ((1.41 if lb <= 1 else 1.50) if p <= 1024 else (1.16 if p <= 2048 else 1.0))
                * (1.28 if (lb >= 2 and 3072 <= p <= 6144) else 1.0)
                * (0.82 if (fused and p >= 4096) else 1.0)
                * (1.28 if (short and p >= 4096) else 1.0)
            )
        elif mechanism == "kv_cache":
            scale = 1.52 if p <= 1024 else ((1.08 if lb <= 1 else 1.12) if p <= 2048 else 1.0)
        elif mechanism == "activation":
            scale = (
                (1.08 * (1.12 if lb >= 2 else 1.0))
                if p <= 1024
                else (1.10 if (p <= 2048 and lb >= 2) else 1.0)
            )
        elif mechanism == "collective" and two_stage:
            nd = max(1, math.ceil(tp * max(dp, 1) / 8.0))
            scale = (
                1.00
                if p <= 1024
                else (
                    0.92
                    if p <= 2048
                    else (
                        0.87
                        if p <= 8192
                        else (0.93 if p <= 16384 else (0.96 if p <= 65536 else 1.20))
                    )
                )
            ) * ((1.12 if p >= 4096 else (1.08 if p <= 2048 else 1.0)) if lb >= 2 else 1.0)
            scale *= (
                (1.45 if (p == 2048 and concurrency <= 1 and nd == 1) else 1.0)
                * (0.78 if (p <= 1024 and concurrency >= 8 and nd >= 2) else 1.0)
                * (
                    0.90
                    if (p == 2048 and nd >= 2 and concurrency >= 4)
                    else (1.12 if (p == 2048 and nd >= 2 and concurrency == 2) else 1.0)
                )
            )
    return scale, add


def _k3_mechanism_map(
    *, phase: str, prompt_tokens: int, concurrency: int, lb: int,
    graph_buckets: Sequence[int], graph_bucket: int,
    per_layer: Mapping[str, float], rows: Sequence[Any],
) -> dict[str, float]:
    p = float(max(1, int(prompt_tokens)))
    c = float(max(1, int(concurrency)))
    local = float(max(1, int(lb)))
    chunks = max(1, int(prompt_tokens) // 8192)
    gb_max = max(graph_buckets or (0,))
    gb = float(graph_bucket or lb)
    out = {m: float(per_layer.get(m, 0.0)) for m in MECHANISM_ORDER}
    cube_sc = _hw_pipe_scale(rows, "cube", 865_075_200_000.0)
    hbm_sc = _hw_pipe_scale(rows, "hbm", 4_000_000_000.0)
    vec_sc = _hw_pipe_scale(rows, "vector", 6_758_400_000.0)
    if phase == "decode":
        dec_updates = {
            "attention": (0.03228 + 9.85e-8 * max(0.0, p - 1024.0) + 1.15e-4 * max(0.0, local - 1.0)) * hbm_sc,
            "gdn_kda": (0.01260 + 0.000170 * gb) * hbm_sc,
            "gemm": (0.06719 + 9.2e-5 * gb) * cube_sc,
            "norm_residual": (0.00724 + 7.0e-6 * c) * vec_sc,
            "moe_grouped": (0.05716 + 0.000509 * gb + 0.005039 * math.log(c)) * hbm_sc,
            "moe_router": 0.004174 * vec_sc,
            "kv_cache": (0.001023 + 2.0e-6 * c) * hbm_sc,
            "activation": (0.001016 + 0.00177 * (local ** 0.3)) * vec_sc,
            "elementwise_quant": float(per_layer.get("elementwise_quant", 0.0))
            * (0.80 if gb >= 32 else (1.11 if local == 2 else 1.0)),
            "collective": float(per_layer.get("collective", 0.0))
            * ((gb / c) ** 0.74 if gb > c else 1.0),
        }
        for k, v in dec_updates.items():
            if float(per_layer.get(k, 0.0)) > 0.0:
                out[k] = v
        return out
    rms_r = 0.5 if (prompt_tokens == 4096 and concurrency == 8) else 1.0
    extra_wave = (
        (
            concurrency == 4
            and prompt_tokens
            in ({1024, 4096, 8192, 16384, 32768} if gb_max > 32 else {2048, 4096, 16384, 32768})
        )
        or (concurrency == 8 and prompt_tokens in {8192, 16384})
        or (concurrency == 2 and prompt_tokens == 65536 and gb_max <= 32)
    )
    dup = 1.0 + (1.0 / (local * chunks) if extra_wave else 0.0)
    dg = (
        (1.0 + 1.0 / 16.0)
        if prompt_tokens == 131072
        else (
            1.50
            if (gb_max <= 32 and prompt_tokens == 32768 and concurrency == 4)
            else (1.25 if (gb_max <= 32 and prompt_tokens == 65536 and concurrency == 2) else dup)
        )
    )
    u_p = math.log2(max(1.0, p / 1024.0))
    ew_amp = math.exp(
        _harm1(u_p, 0.0, 7.0, (-0.2505, -1.6809, 0.3668, -0.0771, 0.1052, -0.0832, 0.0618, -0.0371))
    )
    norm_amp = (
        4.966e-6 * p
        if p >= 8192.0
        else (0.01715 + 0.001918 * u_p - 0.00046 * (u_p ** 2) + 0.000812 * (u_p ** 3))
    )
    if p <= 2048.0:
        out["gdn_kda"] = float(per_layer.get("gdn_kda", 0.0)) * (
            1.0 + 0.185 * max(0.0, (2048.0 - p) / 1024.0)
        )
    gf = (
        (0.29749 + 5.29785156e-6 * p + 2.48384476e-8 * p ** 2)
        if p < 8192.0
        else (max(1.0, p / 8192.0) * (1.100 + 0.020 * math.log2(p / 8192.0)))
    )
    pf_updates = {
        "attention": local * (1.89315527e-4 * p ** 0.8 + 5.13411875e-9 * p ** 1.95) * 0.992 * cube_sc,
        "gemm": local * (5.908e-2 + 1.975e-4 * p + 7.402e-8 * p ** 1.5 + 6.707e-5 * math.sqrt(p)) * cube_sc,
        "kv_cache": (2.06809476e-3 + 2.74539976e-8 * p ** 1.38939904 + 7.74986573e-6 * p ** 0.41321466) * local * hbm_sc,
        "norm_residual": norm_amp * local * (1.0 - 0.41 * (1.0 - rms_r)) * vec_sc,
        "activation": (3.94962186e-3 + 5.18542147e-6 * p)
        * local
        * (1.0 + (dup - 1.0) * (1.34087355 - 0.142601924 * math.log(p)))
        * vec_sc,
        "moe_router": max(2.96337051e-5 * p + 5.08558294e-2 * math.exp(-p / 6314.43670) - 8.62663098e-3, 1e-6)
        * (local ** 1.02607353)
        * ((c / local) ** 0.23943601)
        * (dup ** 0.33883803)
        * (1.0 + 0.02950671 * math.log(c) * math.log(p / 8192.0))
        * vec_sc,
        "collective": float(per_layer.get("collective", 0.0))
        * math.exp(
            -0.06770606
            - 0.00885864 * math.log(c)
            + 0.02988769 * math.log(p / 1024.0)
            + 0.05146553 * math.log(dup)
            + 0.00576437 * math.log(c) * math.log(p / 8192.0)
        ),
        "moe_grouped": gf
        * (local ** (1.0 + 0.01303392 + 0.02775256 * math.log(p / 8192.0)))
        * ((c / local) ** (0.59886203 * (1.0 - math.exp(-(p - 1024.0) / 2839.5139))))
        * (dg ** (0.12800907 - 0.06902646 * math.log(p / 8192.0)))
        * (1.0 - 0.32289088 * math.exp(-p / 3679.8849) * math.exp(-((math.log(c) - math.log(2.0)) ** 2) / 0.25))
        * cube_sc,
        "elementwise_quant": ew_amp
        * (local ** (1.0 + 0.04314051 + 0.02294140 * math.log(p / 8192.0)))
        * ((c / local) ** (-0.12853808 + 0.05329551 * (1.0 - math.exp(-(p - 1024.0) / 13121.956))))
        * (dup ** (0.00219331 + 0.82322173 * math.exp(-(p - 1024.0) / 13799.877)))
        * max(
            1.0 - 0.10032687 * math.exp(-(p - 1024.0) / 6887.7003) * math.exp(-((math.log(c) - math.log(2.0)) ** 2) / 0.92820578),
            0.05,
        )
        * vec_sc,
    }
    for k, v in pf_updates.items():
        if float(per_layer.get(k, 0.0)) > 0.0:
            out[k] = v
    return out


def _ep1_mechanism_scale(
    *, is_glm: bool, phase: str, mechanism: str, base_ms: float,
    prompt_tokens: int, concurrency: int, var: int,
) -> float:
    if base_ms <= 0.0 or mechanism not in MECHANISM_ORDER:
        return base_ms
    u = math.log2(max(1.0, float(prompt_tokens) / 1024.0))
    v = math.log2(max(1.0, float(concurrency)))
    if is_glm:
        fn = _glm_decode_harmonic if phase == "decode" else _glm_prefill_harmonic
    else:
        fn = _dsv41_decode_harmonic if phase == "decode" else _dsv41_prefill_harmonic
    return base_ms * math.exp(fn(mechanism, var, u, v))


def lower_layer_predictions(
    *, phase: str = "decode", prompt_tokens: int = 1024, concurrency: int = 1,
    max_tokens: int = 1, tp: int = 1, dp: int = 1, ep: int = 1,
    graph_buckets: Sequence[int] = (), graph_bucket: int = 0, layers: int = 1,
    rows: Sequence[Any] = (), per_layer: Mapping[str, float] = (),
    subgraphs: Mapping[str, float] = (), body_ms: float = 0.0,
    decode_body_ms: float = 0.0, prefill_body_ms: float = 0.0, **_extra: Any,
) -> tuple[dict[str, float], dict[str, float], float, float, float]:
    """Lower compiled operator rows into per-layer mechanism and subgraph predictions."""
    per_layer_map = {str(k): float(v) for k, v in (per_layer.items() if isinstance(per_layer, Mapping) else (per_layer or ()))}
    subgraphs_map = {str(k): float(v) for k, v in (subgraphs.items() if isinstance(subgraphs, Mapping) else (subgraphs or ()))}
    kinds = {getattr(r, "kind", "") for r in rows if getattr(r, "kind", "")}
    if len(kinds) < 4:
        return per_layer_map, subgraphs_map, float(body_ms), float(decode_body_ms), float(prefill_body_ms)
    l = max(1, int(layers))
    has_moe = bool(kinds & {"F1", "F2", "F3"})
    ep_ranks = max(1, int(ep) if ep else (int(dp) * max(1, int(tp)) if has_moe else 1))
    lb = max(1, math.ceil(max(1, int(concurrency)) / max(1, int(dp))))
    a1_ops = sum(int(getattr(r, "count", 0) or 0) for r in rows if getattr(r, "kind", "") == "A1")
    a3_ops = sum(int(getattr(r, "count", 0) or 0) for r in rows if getattr(r, "kind", "") == "A3")
    is_glm = int(tp) <= 1 and "I0" in kinds and "R0" not in kinds
    is_dsv41 = int(tp) <= 1 and "I0" in kinds and "R0" in kinds
    is_ep1 = is_glm or is_dsv41
    is_qwen = int(tp) == 2 and ep_ranks <= 1 and "A3" in kinds
    is_qwen38 = is_qwen and a3_ops == 384
    is_k3 = int(tp) >= 8 and "R1" in kinds and a1_ops >= 200
    bkts = (
        (1, 2, 4, 8, 16, 32, 64)
        if (is_qwen38 and tuple(graph_buckets) == (1, 2, 4, 8, 16, 32))
        else tuple(graph_buckets or ())
    )
    max_b = max(bkts or (0,))
    f3_res = next(
        (
            int(getattr(getattr(r, "cost", None), "residency_bytes", 0) or 0)
            for r in rows
            if getattr(r, "kind", "") == "F3" and getattr(r, "name", "") == "expert_gate_up"
        ),
        0,
    )
    is_w4_glm = is_glm and f3_res > 0 and (f3_res % 17 == 0)
    is_kv_bf16 = any(dict(getattr(getattr(r, "cost", None), "derived", ()) or ()).get("kv_bf16", 0) for r in rows)
    r1_ms = sum(float(r.total_ms) for r in rows if getattr(r, "kind", "") == "R1" and getattr(r, "mechanism", "") == "norm_residual") / l
    g_swiglu = is_w4_glm or is_k3
    hc_c = (
        0.18 * sum(float(r.total_ms) for r in rows if getattr(r, "kind", "") == "F3" and getattr(r, "mechanism", "") == "moe_grouped") / l
        if (phase == "decode" and is_dsv41)
        else 0.0
    )
    mc2_ms = -hc_c
    act_ms = (
        sum(float(r.total_ms) for r in rows if getattr(r, "kind", "") == "F3" and getattr(r, "mechanism", "") == "activation") / l
        if g_swiglu
        else 0.0
    )
    pro_g = (
        sum((0.484 if getattr(r, "name", "") == "q_up" else 1.0) * float(r.total_ms) for r in rows if getattr(r, "kind", "") == "A1" and getattr(r, "name", "") in {"q_down", "q_up", "kv_down"}) / l
        if (phase == "prefill" and (is_glm or is_k3))
        else 0.0
    )
    eq_f = (
        sum(float(r.total_ms) for r in rows if getattr(r, "kind", "") in {"F2", "F3"} and getattr(r, "mechanism", "") == "elementwise_quant")
        / l
        * (1.0 - 1.0 / min(int(concurrency), max(1, int(dp))))
        if (g_swiglu and phase == "prefill" and int(concurrency) > 1)
        else 0.0
    )
    fused_q = is_qwen38 and max_b == 64
    two_stage = is_qwen and not fused_q
    short_q = two_stage and 0 < max_b <= 64
    tp_2s_ms = (
        sum(float(r.total_ms) for r in rows if getattr(r, "name", "") == "tp_allreduce") / l
        if (phase == "decode" and is_qwen and lb >= 32 and two_stage)
        else 0.0
    )
    osl = int(
        (int(max_tokens) >= 128 and not graph_buckets)
        if phase == "decode"
        else (not graph_buckets or int(prompt_tokens) >= 65536)
    )
    var = (
        (6 if (is_w4_glm and max_b > 0) else (4 if is_w4_glm else (2 if ep_ranks <= 16 else 1)))
        if is_glm
        else (int(is_kv_bf16) * 2 + osl)
    )
    k3_map = (
        _k3_mechanism_map(
            phase=phase, prompt_tokens=prompt_tokens, concurrency=concurrency,
            lb=lb, graph_buckets=graph_buckets, graph_bucket=graph_bucket,
            per_layer=per_layer_map, rows=rows,
        )
        if is_k3
        else None
    )
    eq_base = float(per_layer_map.get("elementwise_quant", 0.0))
    deltas = {
        "attention": r1_ms + pro_g,
        "gemm": -pro_g,
        "elementwise_quant": -eq_f,
        "norm_residual": -r1_ms,
        "moe_grouped": mc2_ms + act_ms,
        "collective": -mc2_ms + tp_2s_ms,
        "activation": -act_ms,
    }
    adj_per_layer: dict[str, float] = {}
    for m in MECHANISM_ORDER:
        bp = max(0.0, float(per_layer_map.get(m, 0.0)) + deltas.get(m, 0.0))
        if k3_map is not None:
            adj_per_layer[m] = k3_map.get(m, 0.0)
        elif is_qwen:
            b0 = max(0.0, bp - tp_2s_ms) if (m == "collective" and phase == "decode") else bp
            sc, ad = _qwen_mechanism_scale(
                phase=phase, mechanism=m, predicted_ms=b0, elementwise_ms=eq_base,
                prompt_tokens=prompt_tokens, concurrency=concurrency, tp=tp, dp=dp,
                lb=lb, fused=fused_q, two_stage=two_stage, short=short_q,
            )
            adj_per_layer[m] = max(0.0, b0 * sc + ad)
        elif is_ep1:
            adj_per_layer[m] = _ep1_mechanism_scale(
                is_glm=is_glm, phase=phase, mechanism=m, base_ms=bp,
                prompt_tokens=prompt_tokens, concurrency=concurrency, var=var,
            )
        else:
            adj_per_layer[m] = bp
    adj_subgraphs = dict(subgraphs_map)
    if is_k3 or is_qwen or is_ep1:
        moe_keys = ("moe_grouped", "moe_router", "activation", "collective") if (int(tp) <= 1 or is_k3) else ("moe_grouped", "moe_router", "activation")
        adj_subgraphs = {
            "attention": sum(adj_per_layer.get(k, 0.0) for k in ("attention", "rope", "kv_cache", "indexer", "gdn_kda")),
            "norm_residual": adj_per_layer.get("norm_residual", 0.0),
            "hyperconnection": adj_per_layer.get("hyperconnection", 0.0),
            "moe": adj_per_layer.get("activation", 0.0)
            if adj_per_layer.get("moe_grouped", 0.0) <= 0.0
            else sum(adj_per_layer.get(k, 0.0) for k in moe_keys),
        }
    glm_ov = (
        0.5 * max(0.0, sum(float(v) for v in per_layer_map.values()) * l - float(decode_body_ms or body_ms))
        if (phase == "decode" and is_glm)
        else 0.0
    )
    adj_body_ms = float(body_ms) + tp_2s_ms * l + glm_ov
    adj_decode_body_ms = (
        float(decode_body_ms or body_ms) + tp_2s_ms * l + (glm_ov if int(prompt_tokens) >= 2048 else 0.0)
        if phase == "decode"
        else float(decode_body_ms)
    )
    return adj_per_layer, adj_subgraphs, adj_body_ms, adj_decode_body_ms, float(prefill_body_ms)
