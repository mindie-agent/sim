def _harm1(x: float, x0: float, span: float, coeffs: Sequence[float]) -> float:
    t = max(0.0, min(1.0, (x - x0) / max(1e-9, span)))
    return sum(c * math.cos(j * math.pi * t) for j, c in enumerate(coeffs))


def _harm2(
    u: float, u0: float, uspan: float, v: float, v0: float, vspan: float,
    cu: Sequence[float], cv: Sequence[float],
    *cross: tuple[Sequence[float], Sequence[float]],
) -> float:
    base = _harm1(u, u0, uspan, cu) + _harm1(v, v0, vspan, cv)
    for cf, cg in cross:
        base += _harm1(u, u0, uspan, cf) * _harm1(v, v0, vspan, cg)
    return base


def _hw_pipe_scale(rows: Sequence[Any], pipe: str, nom_rate: float) -> float:
    for r in rows:
        cost = getattr(r, "cost", None)
        if cost is None:
            continue
        work = dict(getattr(cost, "work", ()) or ())
        times = dict(getattr(cost, "times", ()) or ())
        w_val = float(work.get(pipe, 0.0) or 0.0)
        t_val = float(times.get(pipe, 0.0) or 0.0)
        if w_val > 0.0 and t_val > 0.0:
            eff_rate = w_val / t_val
            if eff_rate > 0.0:
                ratio = nom_rate / eff_rate
                return 1.0 if abs(ratio - 1.0) < 1e-3 else max(0.1, min(10.0, ratio))
    return 1.0


